function dbRowToProduct(row: Record<string, unknown>): Product {
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(row)) {
    if (key === 'created_at') continue; // skip DB-only column
    const camelKey = PRODUCT_DB_TO_CAMEL[key] || key;
    result[camelKey] = value;
  }
  return result as unknown as Product;
}

function productToDbRow(prod: Record<string, unknown>): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(prod)) {
    const dbKey = PRODUCT_CAMEL_TO_DB[key] || key;
    result[dbKey] = value;
  }
  return result;
}

let lastFetchTime = 0;
const FETCH_COOLDOWN = 10000; // 10 seconds cooldown between background refreshes

export function fetchProductsFromSupabase() {
  if (typeof window === 'undefined') return;
  const now = Date.now();
  if (now - lastFetchTime < FETCH_COOLDOWN) return;
  lastFetchTime = now;

  supabase
    .from('products')
    .select('*')
    .order('id', { ascending: true })
    .then(({ data, error }) => {
      if (error) {
        console.error('Failed to sync products from Supabase:', error.message);
        return;
      }
      if (data && data.length > 0) {
        // Map DB lowercase columns to camelCase interface
        const mapped = data.map(row => dbRowToProduct(row as Record<string, unknown>));
        // Safe merge with local default products so new catalog items and local assets are preserved
        const dbMap = new Map(mapped.map(p => [p.id, p]));
        const merged = products.map(p => {
          const fromDb = dbMap.get(p.id);
          return fromDb ? { ...p, ...fromDb, image: p.image } : p;
        });
        localStorage.setItem('dp_products', JSON.stringify(merged));
        window.dispatchEvent(new Event('dp_products_updated'));
      }
    });
}

const CATALOG_VERSION = 'v5_peptides_verified';

export function getStoredProducts(): Product[] {
  if (typeof window === 'undefined') return products;
  
  // Enforce latest catalog version on clients
  const storedVersion = localStorage.getItem('dp_catalog_version');
  if (storedVersion !== CATALOG_VERSION) {
    localStorage.setItem('dp_catalog_version', CATALOG_VERSION);
    localStorage.setItem('dp_products', JSON.stringify(products));
    return products;
  }

  const stored = localStorage.getItem('dp_products');
  
  // Trigger background revalidation fetch
  fetchProductsFromSupabase();

  if (!stored) {
    localStorage.setItem('dp_products', JSON.stringify(products));
    return products;
  }
  try {
    const list: Product[] = JSON.parse(stored);
    const defaultMap = new Map(products.map(p => [p.id, p]));
    let hasChanges = false;
    for (let i = 0; i < list.length; i++) {
      const def = defaultMap.get(list[i].id);
      if (def && def.image !== list[i].image) {
        list[i].image = def.image;
        hasChanges = true;
      }
    }
    const existingIds = new Set(list.map(p => p.id));
    for (const p of products) {
      if (!existingIds.has(p.id)) {
        list.push(p);
        existingIds.add(p.id);
        hasChanges = true;
      }
    }
    if (hasChanges) {
      localStorage.setItem('dp_products', JSON.stringify(list));
    }
    return list;
  } catch (e) {
    return products;
  }
}

export function saveStoredProducts(list: Product[]) {
  if (typeof window !== 'undefined') {
    localStorage.setItem('dp_products', JSON.stringify(list));
    window.dispatchEvent(new Event('dp_products_updated'));
  }
}

export async function addProduct(prod: Omit<Product, 'id' | 'slug'>): Promise<Product> {
  const list = getStoredProducts();
  const nextId = list.length > 0 ? Math.max(...list.map(p => p.id)) + 1 : 1000;
  const slug = `${prod.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${nextId}`;
  const newProduct: Product = {
    ...prod,
    id: nextId,
    slug
  };

  // Convert camelCase to lowercase for DB
  const dbRow = productToDbRow(newProduct as unknown as Record<string, unknown>);
  const { error } = await supabase.from('products').insert([dbRow]);
  if (error) {
    console.error('Supabase add product error:', error.message);
    throw error;
  }

  list.push(newProduct);
  saveStoredProducts(list);
  return newProduct;
}

export async function updateProduct(id: number, updated: Partial<Product>): Promise<boolean> {
  const list = getStoredProducts();
  const idx = list.findIndex(p => p.id === id);
  if (idx === -1) return false;

  const mergedProduct = { ...list[idx], ...updated };

  // Convert camelCase to lowercase for DB
  const dbUpdated = productToDbRow(updated as Record<string, unknown>);
  const { error } = await supabase
    .from('products')
    .update(dbUpdated)
    .eq('id', id);

  if (error) {
    console.error('Supabase update product error:', error.message);
    throw error;
  }

  list[idx] = mergedProduct;
  saveStoredProducts(list);
  return true;
}

export async function deleteProduct(id: number): Promise<boolean> {
  const list = getStoredProducts();
  const filtered = list.filter(p => p.id !== id);
  if (filtered.length === list.length) return false;

  const { error } = await supabase
    .from('products')
    .delete()
    .eq('id', id);

  if (error) {
    console.error('Supabase delete product error:', error.message);
    throw error;
  }

  saveStoredProducts(filtered);
  return true;
}

export function getProductsByCategory(slug: string): Product[] {
  return getStoredProducts().filter(p => p.categorySlug === slug);
}

export function getProductsByBrand(slug: string): Product[] {
  return getStoredProducts().filter(p => p.brandSlug === slug);
}

export function getFeaturedProducts(): Product[] {
  return getStoredProducts().filter(p => p.featured);
}

export function getBestSellers(): Product[] {
  return getStoredProducts().filter(p => p.bestSeller);
}

export function getProductBySlug(slug: string): Product | undefined {
  return getStoredProducts().find(p => p.slug === slug);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return getStoredProducts().filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.substance.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q)
  );
}
